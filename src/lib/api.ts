/**
 * Payment response. Field names mirror Paytm's public Payment Links / Order API
 * shape (`orderId`, `txnAmount`, `merchantId`, `payerVpa`, `txnStatus`) so a live
 * merchant integration is a credentials swap rather than a schema rewrite.
 */
export type PaymentRecord = {
  orderId: string;
  merchantId: number;
  customerId: number;
  txnId: number;
  txnAmount: { value: string; currency: string };
  txnDate: string;
  txnStatus: string;
  respCode: string;
  respMsg: string;
  paymentMode: string;
  payerVpa: string;
  payeeVpa: string;
  payeeName: string;
  txnNote: string;
  /** Real UPI deep links generated by the backend for this order. */
  paytmIntent: string;
  upiIntent: string;
};

export type PaymentResult = {
  ok: boolean;
  payment?: PaymentRecord;
  transaction: Transaction;
  relationship: Relationship;
};

async function request<T>(path: string): Promise<T> {
  const response = await fetch(`${import.meta.env.VITE_API_BASE_URL ?? "/api"}${path}`);
  if (!response.ok) {
    throw new Error(`API request failed: ${response.status}`);
  }
  return response.json();
}

export const api = {
  customers: () => request<Customer[]>("/customers"),
  merchants: () => request<Merchant[]>("/merchants"),
  stats: () => request<DemoStats>("/stats"),
  customer: (id: number) => request<Customer>(`/customers/${id}`),
  merchant: (id: number) => request<Merchant>(`/merchants/${id}`),
  customerTransactions: (id: number) => request<Transaction[]>(`/customers/${id}/transactions`),
  merchantTransactions: (id: number) => request<Transaction[]>(`/merchants/${id}/transactions`),
  relationship: (customerId: number, merchantId: number) => request<Relationship>(`/relationship/${customerId}/${merchantId}`),
  pulse: (merchantId: number) => request<Pulse>(`/merchant/${merchantId}/pulse`),
  pricing: (merchantId: number) => request<PricingInsight[]>(`/merchant/${merchantId}/pricing`),
  rewardOffer: (customerId: number) => request<RewardOffer>(`/rewards/${customerId}/multiplier`),
  merchantRewards: (merchantId: number) => request<MerchantRewardSummary>(`/merchant/${merchantId}/rewards`),
  loanReadiness: (merchantId: number) => request<LoanReadiness>(`/merchant/${merchantId}/loan-readiness`),
  resetDemo: () => fetch(`${import.meta.env.VITE_API_BASE_URL ?? "/api"}/reset-demo`, { method: "POST" }),
  // Request body uses Paytm's public Payment Links / Order API field naming
  // (`merchantId`, `customerId`, `txnAmount: {value, currency}`, `paymentMode`)
  // so a real Paytm merchant integration can replace this call with minimal changes.
  createPayment: (customerId: number, merchantId: number, amount: number, txnNote?: string) =>
    fetch(`${import.meta.env.VITE_API_BASE_URL ?? "/api"}/payments`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        merchantId,
        customerId,
        txnAmount: { value: amount.toFixed(2), currency: "INR" },
        paymentMode: "UPI",
        txnNote
      })
    }).then((response) => {
      if (!response.ok) throw new Error("Payment failed");
      return response.json() as Promise<PaymentResult>;
    }),
  redeemReward: (customerId: number, offer: string, points: number) =>
    fetch(`${import.meta.env.VITE_API_BASE_URL ?? "/api"}/rewards/${customerId}/redeem`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ offer, points })
    }).then((response) => {
      if (!response.ok) throw new Error("Reward redemption failed");
      return response.json() as Promise<{ ok: boolean; reward: RewardOffer }>;
    }),
  acceptPricing: (merchantId: number, sku: string) =>
    fetch(`${import.meta.env.VITE_API_BASE_URL ?? "/api"}/merchant/${merchantId}/pricing/actions`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ sku, action: "accept" })
    })
};

export const rupees = (amount: number) =>
  new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 0 }).format(amount);
